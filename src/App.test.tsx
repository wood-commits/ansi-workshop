      fireEvent.pointerDown(bar.firstElementChild!, { button: 0, clientY: 50 })
      fireEvent[stop](bar)
      fireEvent.pointerMove(bar, { clientY: 350 })
      expect(bar.getAttribute('aria-valuenow')).toBe('0')
